#!/usr/bin/env node
/**
 * Merge softwareInnerHero.imageSrc from content/odoo-json into data/software-product-media.ts
 * for slugs missing from SOFTWARE_PRODUCT_HERO_IMAGES.
 */
import fs from "fs";
import path from "path";

const ROOT = path.resolve(import.meta.dirname, "..");
const JSON_ROOT = path.join(ROOT, "content", "odoo-json");
const MEDIA_TS = path.join(ROOT, "data", "software-product-media.ts");

function walkJson(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walkJson(p, out);
    else if (ent.name.endsWith(".json")) out.push(p);
  }
  return out;
}

const mediaText = fs.readFileSync(MEDIA_TS, "utf8");
const heroBlock = mediaText.match(/export const SOFTWARE_PRODUCT_HERO_IMAGES[^=]*=\s*\{([\s\S]*?)\n\};/);
if (!heroBlock) throw new Error("SOFTWARE_PRODUCT_HERO_IMAGES block not found");

const existing = new Map(
  [...heroBlock[1].matchAll(/"([^"]+)"\s*:\s*"([^"]+)"/g)].map((m) => [m[1], m[2]]),
);

const added = [];
for (const file of walkJson(JSON_ROOT)) {
  const slug = path.basename(file, ".json");
  if (existing.has(slug)) continue;
  let data;
  try {
    data = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    continue;
  }
  const src =
    data.softwareInnerHero?.imageSrc ??
    data.softwareInnerHero?.introRows?.[0]?.imageSrc ??
    data.hero?.imageSrc ??
    data.banner?.imageSrc;
  if (!src || !/^https?:\/\//.test(src)) continue;
  existing.set(slug, src);
  added.push(slug);
}

const lines = [...existing.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, url]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(url)},`)
  .join("\n");

const familiesMatch = mediaText.match(/export const SOFTWARE_FAMILIES[\s\S]*?;\n/);
const tailMatch = mediaText.match(/\nexport function softwareHeroImage[\s\S]*$/);
if (!familiesMatch || !tailMatch) throw new Error("Unexpected software-product-media.ts shape");

const next = `/** Auto-generated by scripts/extract-software-live.mjs — do not edit by hand */\n\n${familiesMatch[0]}\nexport const SOFTWARE_PRODUCT_HERO_IMAGES: Record<string, string> = {\n${lines}\n};\n${tailMatch[0]}`;

fs.writeFileSync(MEDIA_TS, next);
console.log(`Hero map: ${existing.size} slugs (+${added.length} from JSON): ${added.join(", ") || "none"}`);
