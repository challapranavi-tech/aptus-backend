#!/usr/bin/env node
/**
 * Extract every unique Font Awesome icon (viewBox + inner <path>s) used across the
 * live ELV pages and emit data/elv-icons.ts. The ELV product cards then render the
 * exact same SVG as the live site, keyed by the FA icon name (e.g. "thermometer-half").
 *
 * Usage: node scripts/extract-elv-icons.mjs
 */
import fs from "fs";
import path from "path";

const ROOT = path.resolve(import.meta.dirname, "..");
const LIVE = path.join(ROOT, "LIVE WEBSITE", "ELV");
const OUT = path.join(ROOT, "data", "elv-icons.ts");

const icons = {};
const re =
  /<svg[^>]*class="[^"]*e-fa[brs]-([a-z0-9-]+)[^"]*"[^>]*viewBox="([^"]+)"[^>]*>([\s\S]*?)<\/svg>/gi;

for (const file of fs.readdirSync(LIVE)) {
  if (!file.endsWith(".html")) continue;
  const html = fs.readFileSync(path.join(LIVE, file), "utf8");
  let m;
  while ((m = re.exec(html))) {
    const [, name, viewBox, inner] = m;
    if (icons[name]) continue;
    // keep only <path .../> elements, drop any fill so it inherits currentColor
    const paths = [...inner.matchAll(/<path\b[^>]*?\/?>(?:<\/path>)?/gi)]
      .map((p) =>
        p[0]
          .replace(/\s*fill="[^"]*"/gi, "")
          .replace(/<\/path>/gi, "")
          .replace(/\s*\/?>$/, "/>"),
      )
      .join("");
    if (!paths) continue;
    icons[name] = { viewBox, paths };
  }
}

const names = Object.keys(icons).sort();
const body = names
  .map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/extract-elv-icons.mjs — do not edit by hand.
// Exact Font Awesome SVGs lifted from the live ELV pages so cards render identically.
export interface ElvIcon {
  viewBox: string;
  paths: string;
}

export const ELV_ICONS: Record<string, ElvIcon> = {
${body}
};
`;

fs.writeFileSync(OUT, out);
console.log(`Wrote ${names.length} icons -> ${path.relative(ROOT, OUT)}`);
console.log(names.join(", "));
