function SoftwareSectionHeading({
  heading,
  headingAccent,
  subheading,
  leadMuted,
  align = "center",
}: Pick<FeaturesData, "heading" | "headingAccent" | "subheading" | "align"> & { leadMuted?: boolean }) {
  const title = [heading, headingAccent].filter(Boolean).join(" ");
  if (!title && !subheading) return null;
  const centered = align !== "left";

  return (
    <div
      className={cn(
        "aptus-software-section-heading",
        centered ? "mx-auto max-w-3xl text-center" : "text-start",
      )}
    >
      {title && <h2 className="aptus-software-section-title">{title}</h2>}
      {subheading && (
        <p
          className={
            leadMuted ? "aptus-software-value-lead mt-3" : "aptus-software-section-lead"
          }
        >
          {subheading}
        </p>
      )}
    </div>
  );
}

